export function sellerLines(s: Settings): string[] {
  const lines: string[] = [];
  if (s.seller_name) lines.push(`Продавець: ${s.seller_name}`);
  if (s.seller_tax_id) lines.push(`РНОКПП / ЄДРПОУ: ${s.seller_tax_id}`);
  if (s.seller_address) lines.push(`Адреса: ${s.seller_address}`);
  if (s.contact_phone) lines.push(`Телефон: ${s.contact_phone}`);
  if (s.contact_email) lines.push(`Email: ${s.contact_email}`);
  if (s.work_hours) lines.push(`Графік роботи: ${s.work_hours}`);
  return lines;
}

const sellerBlock = (s: Settings) => {
  const lines = sellerLines(s);
  return lines.length
    ? lines.map((l) => `- ${l}`).join("\n")
    : "Реквізити продавця будуть опубліковані до початку продажів.";
};

const contactHint = (s: Settings) =>
  [s.contact_phone && `за телефоном ${s.contact_phone}`, s.contact_email && `на email ${s.contact_email}`]
    .filter(Boolean)
    .join(" або ") || "через сторінку «Контакти»";

